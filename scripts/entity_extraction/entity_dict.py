def find_canonical_name(name: str, entity_type: str) -> str:
    """Find the canonical name for an entity."""
    if entity_type == "Person":
        for canonical, aliases in PERSON_DICT.items():
            if name in aliases:
                return canonical
    elif entity_type == "Place":
        for canonical, aliases in PLACE_DICT.items():
            if name in aliases:
                return canonical
    elif entity_type == "Group":
        for canonical, aliases in GROUP_DICT.items():
            if name in aliases:
                return canonical
    return name
